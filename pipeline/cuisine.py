"""가게 이름(BSSH_NM)으로 배달 종목을 추정한다.

shortcut: 이름 키워드 추정이라 '○○성' 같은 중국집이나 브랜드 미등록 치킨집은 빠진다.
          인허가 데이터의 업태구분(중국식 등)을 붙이면 그걸로 교체한다.
"""
CUISINES = {
    "중식": ("반점", "중화", "중국", "짜장", "짬뽕", "마라", "차이나", "홍콩", "북경", "상해", "탕수육", "객잔", "딤섬"),
    "치킨": ("치킨", "통닭", "닭강정", "교촌", "굽네", "네네", "페리카나", "호식이", "처갓집", "멕시카나",
             "또래오래", "자담", "푸라닭", "60계", "BBQ", "bbq", "BHC", "bhc", "비비큐", "비에이치씨"),
    "피자": ("피자", "도미노", "파파존스"),
    "족발보쌈": ("족발", "보쌈"),
}


def cuisines(name):
    """한 가게가 여러 종목일 수 있다 (예: '닭강정탕수육'). 해당 없으면 빈 리스트."""
    return [c for c, words in CUISINES.items() if any(w in name for w in words)]
